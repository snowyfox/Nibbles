#!/usr/bin/env python3
"""Generate the base's table of WLED's built-in palettes from a WLED checkout.

    python3 tools/wled_palettes.py [/Volumes/Code/WLED-16]

Writes firmware/base/main/wled_palettes.c and .h: each palette's name (in
WLED's palette id order) and its 16 colours, made the way WLED makes them
(CRGBPalette16 from a FastLED palette or from a gradient, fastled_slim.h),
for the base's palette viewer. Reads the WLED sources only.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "base", "main")


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def main():
    wled = sys.argv[1] if len(sys.argv) > 1 else "/Volumes/Code/WLED-16"
    src = os.path.join(wled, "wled00")
    fx = open(os.path.join(src, "FX_fcn.cpp")).read()
    names_block = re.search(r'JSON_palette_names\[\] PROGMEM = R"=====\((.*?)\)====="', fx, re.S).group(1)
    names = re.findall(r'"([^"]*)"', names_block)

    fl = open(os.path.join(src, "src", "dependencies", "fastled_slim", "fastled_slim.h")).read()
    named = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"\b([A-Z][A-Za-z]+)=0x([0-9A-Fa-f]{6})\b", fl)}

    pal = strip_comments(open(os.path.join(src, "palettes.cpp")).read())
    p16 = {}
    for m in re.finditer(r"TProgmemRGBPalette16\s+(\w+)\s+PROGMEM\s*=\s*\{(.*?)\};", pal, re.S):
        cols = []
        for item in [x.strip() for x in m.group(2).split(",") if x.strip()]:
            cols.append(named[item[6:]] if item.startswith("CRGB::") else int(item, 16))
        assert len(cols) == 16, m.group(1)
        p16[m.group(1)] = [((c >> 16) & 255, (c >> 8) & 255, c & 255) for c in cols]
    grad = {}
    for m in re.finditer(r"const\s+(?:uint8_t|byte)\s+(\w+)\[\]\s+PROGMEM\s*=\s*\{(.*?)\};", pal, re.S):
        nums = [int(x) for x in re.findall(r"\d+", m.group(2))]
        grad[m.group(1)] = [tuple(nums[i:i + 4]) for i in range(0, len(nums), 4)]
    fastled_order = re.findall(r"&(\w+)", re.search(r"fastledPalettes\[\] PROGMEM = \{(.*?)\};", pal, re.S).group(1))
    grad_order = re.findall(r"(\w+)", re.search(r"gGradientPalettes\[\] PROGMEM = \{(.*?)\};", pal, re.S).group(1))

    def from_gradient(stops):
        """CRGBPalette16::operator=(gradient), as fastled_slim.h does it."""
        e = [(0, 0, 0)] * 16
        count = len(stops)   # up to and including the stop at 255
        for i, s in enumerate(stops):
            if s[0] == 255:
                count = i + 1
                break

        def fill(a, ca, b, cb):
            if b < a:
                a, b, ca, cb = b, a, cb, ca
            div = (b - a) or 1
            d = [((cb[k] - ca[k]) << 16) // div if cb[k] >= ca[k] else -(((ca[k] - cb[k]) << 16) // div) for k in range(3)]
            acc = [ca[k] << 16 for k in range(3)]
            for i in range(a, b + 1):
                e[i] = tuple(acc[k] >> 16 for k in range(3))
                acc = [acc[k] + d[k] for k in range(3)]

        last = -1
        start = stops[0][1:]
        istart = 0
        j = 0
        while istart < 255:
            j += 1
            iend, col = stops[j][0], stops[j][1:]
            s8, e8 = istart // 16, iend // 16
            if count < 16:
                if s8 <= last < 15:
                    s8 = last + 1
                    e8 = max(e8, s8)
                last = e8
            fill(s8, start, e8, col)
            istart, start = iend, col
        return e

    pals = []
    for pid, name in enumerate(names):
        if pid == 0:
            pals.append((name, 1, p16["PartyColors_gc22"]))      # the effect's own; Party unless it has one
        elif pid < 6:
            pals.append((name, 2, [(0, 0, 0)] * 16))             # made from the effect's colours
        elif pid < 6 + len(fastled_order):
            pals.append((name, 0, p16[fastled_order[pid - 6]]))
        else:
            pals.append((name, 0, from_gradient(grad[grad_order[pid - 6 - len(fastled_order)]])))
    assert len(pals) == 6 + len(fastled_order) + len(grad_order), "names and palettes disagree"

    h = f"""// WLED's built-in palettes (generated by tools/wled_palettes.py from WLED
// {os.path.basename(wled.rstrip('/'))}: do not edit). Index = WLED palette id.
#pragma once

#include <stdint.h>

#define WLED_PALETTE_COUNT {len(pals)}

enum {{
    WLED_PAL_FIXED = 0,     // these 16 colours
    WLED_PAL_DEFAULT = 1,   // the effect's own palette; these colours (Party) when it has none
    WLED_PAL_DYNAMIC = 2,   // made from the effect's colours: no colours here
}};

typedef struct {{
    const char *name;
    uint8_t kind;
    uint8_t rgb[16][3];     // a CRGBPalette16, as WLED makes it
}} wled_palette_t;

extern const wled_palette_t wled_palettes[WLED_PALETTE_COUNT];
"""
    c = ["// Generated by tools/wled_palettes.py: do not edit.", '#include "wled_palettes.h"', "",
         "const wled_palette_t wled_palettes[WLED_PALETTE_COUNT] = {"]
    for name, kind, rgb in pals:
        cols = ", ".join("{%d,%d,%d}" % t for t in rgb)
        c.append(f'    {{ "{name}", {kind}, {{ {cols} }} }},')
    c.append("};")
    open(os.path.join(OUT, "wled_palettes.h"), "w").write(h)
    open(os.path.join(OUT, "wled_palettes.c"), "w").write("\n".join(c) + "\n")
    print(f"{len(pals)} palettes -> {os.path.relpath(OUT)}/wled_palettes.[ch]")


if __name__ == "__main__":
    main()
